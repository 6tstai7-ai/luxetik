function chosenLang() {
  const query = new URLSearchParams(location.search).get("lang");
  if (query === "en" || query === "fr") return query;
  try {
    const saved = localStorage.getItem("luxetik-lang");
    if (saved === "en" || saved === "fr") return saved;
  } catch (error) {
    /* private mode */
  }
  return "fr";
}

function t(key) {
  const lang = document.documentElement.lang === "en" ? "en" : "fr";
  return copy[lang][key] || copy.fr[key] || key;
}

function applyLang(next) {
  document.documentElement.lang = next;
  try { localStorage.setItem("luxetik-lang", next); } catch (error) { /* private mode */ }
  const url = new URL(location.href);
  url.searchParams.set("lang", next);
  history.replaceState(null, "", url);
  document.title = t("title");
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", t("description"));
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    const on = button.dataset.setLang === next;
    button.setAttribute("aria-pressed", on ? "true" : "false");
  });
  document.dispatchEvent(new Event("luxetik:lang"));
}

window.luxetikT = t;

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLang(button.dataset.setLang));
});

applyLang(chosenLang());
